# Hardware inventory of a phone running our Linux (netroot or installed),
# for porting work: what probed, what's missing, what's waiting on what.
#
#   tools/recon/linux-hw-inventory.sh <outdir>
#   tools/recon/linux-hw-inventory.sh --summary <outdir>   (rewrite summary.md
#                                                            from <outdir>/raw)
#
# Runs linux-hw-collect.sh on the phone over SSH (tools/fap-dev ssh), unpacks
# its tar into <outdir>/raw/, decompiles the live device tree with dtc if
# installed, and writes <outdir>/summary.md. Read-only on the phone.
# raw/ holds serial numbers and MAC addresses: don't commit it.
# The Android-side counterpart is tools/recon/android-recon.sh.
set -euo pipefail

here=$(cd "$(dirname "$0")" && pwd)
FAP_DEV=${FAP_DEV:-$here/../fap-dev}
usage="usage: $0 [--summary] <outdir>"
summary_only=0
[ "${1:-}" = --summary ] && { summary_only=1; shift; }
out=${1:?$usage}
R=$out/raw

if [ "$summary_only" = 0 ]; then
    mkdir -p "$R"
    "$FAP_DEV" ssh 'sh -s' < "$here/linux-hw-collect.sh" | tar -xf - -C "$R"
    if [ -f "$R/fdt.dtb" ] && command -v dtc >/dev/null; then
        dtc -q -I dtb -O dts -o "$out/device-tree.dts" "$R/fdt.dtb" 2>/dev/null || true
    fi
fi
[ -d "$R" ] || { echo "no $R" >&2; exit 1; }

block() { echo '```'; cat; echo '```'; }
# grep that doesn't trip set -e/pipefail when nothing matches.
g() { grep "$@" || true; }
# Lines of a raw file, or a note when it is missing or empty.
raw() { if [ -s "$R/$1" ]; then cat "$R/$1"; else echo "(no $1)"; fi; }

{
    echo "# Hardware inventory, $(date '+%Y-%m-%d %H:%M')"
    echo
    echo "Generated by tools/recon/linux-hw-inventory.sh. Raw files: raw/ (contains serials/MACs, don't commit)."
    echo
    echo "## Board"
    {
        raw model.txt
        raw uname.txt
        g -E '^(machine|soc_id|family|revision):' "$R/soc.txt" 2>/dev/null
        echo "cpus: $(grep -c '^processor' "$R/cpuinfo.txt" 2>/dev/null || true)"
        g -m1 MemTotal "$R/meminfo.txt" 2>/dev/null
        echo "cmdline: $(raw cmdline.txt)"
        echo "modules loaded: $(wc -l < "$R/modules.txt" 2>/dev/null | tr -d ' ')"
    } | block

    echo; echo "## Deferred devices"
    if [ -s "$R/deferred.txt" ]; then block < "$R/deferred.txt"; else echo "(none)"; fi

    echo; echo "## Hidden dependencies (see tools/fap-dev audit)"
    {
        if [ -s "$R/clk-summary.txt" ]; then
            echo "clocks on in hardware but unclaimed:"
            awk 'NR>3 && $2==0 && $9=="Y" {print "  " $1}' "$R/clk-summary.txt"
        fi
        echo "dummy regulators:"
        g "using dummy regulator" "$R/dmesg.txt" 2>/dev/null | sed 's/^\[[ 0-9.]*\] /  /' | sort -u
    } | block

    echo; echo "## Remote processors"; raw remoteproc.txt | block
    echo; echo "## Display (DRM connectors) and backlight"; { raw drm.txt; raw backlight.txt; } | block
    echo; echo "## Input"
    g '^N: Name=' "$R/input.txt" 2>/dev/null | sed 's/^N: Name=//' | block
    echo; echo "## Network interfaces"; raw net.txt | block
    echo; echo "## IIO (ADCs, sensors)"; raw iio.txt | block
    echo; echo "## Power supplies"
    g -E '^== |POWER_SUPPLY_(TYPE|STATUS|CAPACITY|VOLTAGE_NOW|ONLINE)=' "$R/power-supply.txt" 2>/dev/null | block
    echo; echo "## Thermal zones"; raw thermal.txt | g -v '^== ' | block
    echo; echo "## Sound cards"; raw sound.txt | g -v '^== ' | block
    echo; echo "## USB device controller"; raw udc.txt | block
    echo; echo "## Firmware loading"; raw firmware-log.txt | sed 's/^\[[ 0-9.]*\] //' | block
    echo; echo "## Files"; echo
    (cd "$R" && find . -maxdepth 1 -type f | sort | sed 's|^\./|- raw/|')
    if [ -f "$out/device-tree.dts" ]; then echo "- device-tree.dts (decompiled from raw/fdt.dtb)"; fi
} > "$out/summary.md"

echo "wrote $out/summary.md"
