#!/usr/bin/env bash
# SPDX-License-Identifier: AGPL-3.0-or-later
# shellcheck disable=SC2016  # code in single quotes runs elsewhere (phone shell, awk), on purpose
#
# Read-only survey of a phone running Android (stock or custom ROM) over adb,
# the first thing to run on a new phone before planning a port.
#
#   tools/recon/android-recon.sh <outdir>
#   tools/recon/android-recon.sh --summary <outdir>    (rewrite summary.md
#                                                        from <outdir>/raw)
#
# Writes <outdir>/raw/ (getprop.txt and a few /proc and /sys listings; holds
# serial numbers, IMEI-adjacent props: never commit or publish it) and
# <outdir>/summary.md (no serials). Needs USB debugging on. Runs only
# getprop, cat, ls, uname, pm and dumpsys: nothing is written to the phone.
# Bootloader-side counterpart (phone in fastboot): tools/fap-dev state.
#
# Environment: ADB (default adb), ADB_SERIAL (pick a phone).
set -euo pipefail

ADB=${ADB:-adb}
usage="usage: $0 [--summary] <outdir>"
summary_only=0
[ "${1:-}" = --summary ] && { summary_only=1; shift; }
out=${1:?$usage}
R=$out/raw

a() { if [ -n "${ADB_SERIAL:-}" ]; then "$ADB" -s "$ADB_SERIAL" "$@"; else "$ADB" "$@"; fi; }
# One read-only shell command into a raw file; errors (permission denied on
# user builds) are kept in the file, not fatal.
grab() { local f=$1; shift; a shell "$*" > "$R/$f" 2>&1 || true; }

if [ "$summary_only" = 0 ]; then
    state=$(a get-state 2>/dev/null || true)
    [ "$state" = device ] || { echo "android-recon: no adb device (state: ${state:-none}); USB debugging on?" >&2; exit 1; }
    mkdir -p "$R"
    grab getprop.txt getprop
    grab uname.txt uname -a
    grab cmdline.txt cat /proc/cmdline
    grab cpuinfo.txt cat /proc/cpuinfo
    grab meminfo.txt cat /proc/meminfo
    grab partitions.txt cat /proc/partitions
    grab by-name.txt 'ls -l /dev/block/by-name/ /dev/block/bootdevice/by-name/ 2>&1'
    grab mounts.txt cat /proc/mounts
    grab drm.txt 'ls /sys/class/drm/'
    grab input.txt cat /proc/bus/input/devices
    grab features.txt pm list features
    grab battery.txt dumpsys battery
    grab soc.txt 'for f in /sys/devices/soc0/*; do [ -f "$f" ] && echo "${f##*/}: $(cat "$f")"; done'
fi
[ -f "$R/getprop.txt" ] || { echo "android-recon: no $R/getprop.txt" >&2; exit 1; }

# getprop's "[key]: [value]" format.
prop() {
    awk -v k="[$1]:" 'index($0, k) == 1 { v = substr($0, length(k) + 2); sub(/^\[/, "", v); sub(/\]$/, "", v); print v; exit }' "$R/getprop.txt"
}
row() { local v; v=$(prop "$2"); [ -z "$v" ] || printf '| %s | %s | `%s` |\n' "$1" "$v" "$2"; }

# Partitions that are boot chain / firmware / identity on Qualcomm or Tensor
# phones: an A/B OTA list that contains them means a slot switch also
# switches bootloaders (anti-rollback!).
DANGER="abl bl1 bl2 bl31 gcf gsa gsa_bl1 ldfw pbl tzsw xbl xbl_config tz hyp rpm aop devcfg keymaster modem radio bootloader"

{
    echo "# Android recon: $(prop ro.product.model) ($(prop ro.product.device)), $(date '+%Y-%m-%d')"
    echo
    echo "Generated by tools/recon/android-recon.sh. Raw files in raw/ hold serials: never commit them."
    echo
    echo "| | value | property |"
    echo "|---|---|---|"
    row "Model" ro.product.model
    row "Brand" ro.product.brand
    row "Manufacturer" ro.product.manufacturer
    row "Device (codename)" ro.product.device
    row "Board" ro.product.board
    row "Platform" ro.board.platform
    row "Hardware" ro.hardware
    row "SoC manufacturer" ro.soc.manufacturer
    row "SoC model" ro.soc.model
    row "Hardware SKU" ro.boot.hardware.sku
    row "Hardware revision" ro.boot.hardware.revision
    row "Project name (OnePlus/Oppo)" ro.boot.project_name
    row "Android" ro.build.version.release
    row "Build" ro.build.id
    row "Fingerprint" ro.build.fingerprint
    row "Security patch" ro.build.version.security_patch
    row "Vendor security patch" ro.vendor.build.security_patch
    row "First API level" ro.product.first_api_level
    row "Bootloader" ro.bootloader
    row "Baseband" gsm.version.baseband
    row "Active slot" ro.boot.slot_suffix
    row "Bootloader locked" ro.boot.flash.locked
    row "Verified boot state" ro.boot.verifiedbootstate
    row "vbmeta device state" ro.boot.vbmeta.device_state
    row "Dynamic partitions" ro.boot.dynamic_partitions
    row "Virtual A/B" ro.virtual_ab.enabled
    row "Treble" ro.treble.enabled
    row "Boot image header" ro.boot.boot_image_header_version
    row "Kernel (GKI?)" ro.kernel.version
    echo
    echo "Kernel: \`$(head -n1 "$R/uname.txt" 2>/dev/null)\`"
    echo
    echo "## Notes for porting"
    [ "$(prop ro.boot.flash.locked)" = 1 ] && echo "- Bootloader is **locked**: unlocking wipes data. Back up first."
    [ "$(prop ro.boot.dynamic_partitions)" = true ] && echo "- Dynamic partitions: vendor/odm live inside \`super\` (tools/recon/lp-parse.py, extract-from-super.sh)."
    ab=$(prop ro.product.ab_ota_partitions)
    if [ -n "$ab" ]; then
        risky=""
        for p in $DANGER; do
            case ",$ab," in *",$p,"*) risky="$risky $p" ;; esac
        done
        echo "- A/B OTA partitions: \`$ab\`"
        [ -n "$risky" ] && echo "- Boot chain/firmware is A/B here (${risky# }): both slots must keep the same bootloader version; never switch to a slot whose bootloader is older (anti-rollback)."
    fi
    echo "- Next: \`fastboot getvar all\` from the bootloader (tools/fap-dev state)."
    echo
    echo "## Files"
    echo
    (cd "$R" && find . -maxdepth 1 -type f | sort | sed 's|^\./|- raw/|')
} > "$out/summary.md"
echo "wrote $out/summary.md"
