"""Pin the exact Fedora packages and base images our images are built from.

    tools/update/lock.py                     every target in targets.yaml
    tools/update/lock.py --target netroot    one target
    tools/update/lock.py --out DIR           write somewhere else than lock/
    tools/update/lock.py --list-steps        show the extracted dnf steps only

For each target (tools/update/targets.yaml) it
  1. extracts the `dnf5 install/remove` commands from the target's
     Containerfiles/build scripts (extract_steps below),
  2. pulls the base image and records its digest,
  3. resolves those steps on top of the base image's rpmdb with libdnf5
     inside a container (tools/update/dnf-helper.py; nothing is installed),
  4. writes lock/<target>.rpms.lock.yaml (what and from where),
     lock/<target>.versionlock.toml (dnf5's versionlock format, what a
     pinned build installs) and lock/<target>.images.env (digests).

Needs podman and PyYAML. Resolution is for the container's architecture;
we refuse anything but aarch64 (on the Mac's podman machine and on the
ubuntu-24.04-arm runners that is native).

Why not konflux's rpm-lockfile-prototype: docs/updates.md ("Evaluation").
Known simplification: one transaction per target, so `install_weak_deps`
is the most permissive of the target's steps (all off since decision 0003:
layers install their `packages` lists without weak deps).
"""
import argparse
import json
import os
import shlex
import subprocess
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import updatelib as ul  # noqa: E402

TARGETS = ul.REPO / "tools/update/targets.yaml"
HELPER_DIR = ul.REPO / "tools/update"
ARCH = "aarch64"
PODMAN = os.environ.get("PODMAN", "podman")
CACHE_VOLUME = "fap-update-dnf-cache"
HEADER = """\
# SPDX-License-Identifier: AGPL-3.0-or-later
# Generated by tools/update/lock.py from tools/update/targets.yaml; do not
# edit. Update: tools/update/check-updates.py --write (docs/updates.md).
"""

# --------------------------------------------------------------- extraction

DNF = {"dnf", "dnf5"}
CONTROL = {"&&", "||", ";", "|", "&", "(", ")", "then", "do", "else", "fi", "done"}


def logical_lines(text):
    """Join backslash continuations; yields (first line number, text)."""
    buf, start = [], None
    for n, line in enumerate(text.splitlines(), 1):
        if start is None:
            start = n
        if line.rstrip().endswith("\\"):
            buf.append(line.rstrip()[:-1])
            continue
        buf.append(line)
        yield start, " ".join(buf)
        buf, start = [], None
    if buf:
        yield start, " ".join(buf)


def tokens(line):
    lex = shlex.shlex(line, posix=True, punctuation_chars=";&|()")
    lex.whitespace_split = True
    lex.commenters = "#"
    try:
        return list(lex)
    except ValueError:      # unbalanced quotes etc.: not a command we can use
        return []


def extract_steps(text, filename="?"):
    """The dnf install/remove commands in a shell script or Containerfile,
    in order: [{"action", "specs", "weak_deps", "where", "skipped"}].
    Specs containing shell variables are skipped (and reported), since we
    can't know their value."""
    steps = []
    for lineno, line in logical_lines(text):
        toks = tokens(line)
        i = 0
        while i < len(toks):
            if toks[i] not in DNF:
                i += 1
                continue
            j = i + 1
            cmd, specs, skipped, weak = None, [], [], None
            while j < len(toks) and toks[j] not in CONTROL:
                t = toks[j]
                if t.startswith("-"):
                    if t.startswith("--setopt=install_weak_deps="):
                        weak = t.split("=", 2)[2].lower() in ("1", "true", "yes")
                elif cmd is None:
                    cmd = t
                elif "$" in t or "`" in t:
                    skipped.append(t)
                else:
                    specs.append(t)
                j += 1
            if cmd in ("install", "remove", "erase"):
                steps.append({
                    "action": "remove" if cmd == "erase" else cmd,
                    "specs": specs,
                    # dnf5's default (install_weak_deps=True) unless set
                    "weak_deps": True if weak is None else weak,
                    "where": "%s:%d" % (filename, lineno),
                    "skipped": skipped,
                })
            i = j
    return steps


def packages_step(text, filename="?"):
    """A layer's package list (tools/image/install-packages): one install
    step, always without weak deps. `#` starts a comment."""
    specs = []
    for line in text.splitlines():
        specs += line.split("#", 1)[0].split()
    return {"action": "install", "specs": specs, "weak_deps": False,
            "where": "%s:1" % filename, "skipped": []}


NETROOT = "boot/android-bootimg/netroot/Containerfile"


def layer_sources(layers, target, with_build):
    """Per layer, in order: packages, packages.<target>, and (bootc images)
    the build script. Dev roots skip build scripts: by convention they only
    configure, except a device's kernel swap, which is image-only."""
    out = []
    for l in layers:
        names = ["packages", "packages." + target] + (["build"] if with_build else [])
        out += [l + "/" + n for n in names if (ul.REPO / l / n).exists()]
    return out


def target_sources(target):
    """A target's source files, in build order.
      sources: [...]                  as listed (Containerfiles, scripts)
      kind: devroot + device/desktop  the netroot, then the layers' package
                                      lists (make-devroot.sh)
      device + desktop                bootc image: the layers in Containerfile
                                      order, boot method from device.env
    Both layered kinds take an optional `layers:` list (opt-in layers/)."""
    if "sources" in target:
        return list(target["sources"])
    extra = ["layers/" + l for l in target.get("layers") or []]
    if target.get("kind") == "devroot":
        layers = ["base", "desktops/" + target["desktop"]] + extra + ["devices/" + target["device"]]
        return [NETROOT] + layer_sources(layers, "devroot", with_build=False)
    env = (ul.REPO / "devices" / target["device"] / "device.env").read_text(encoding="utf-8")
    boot = None
    for line in env.splitlines():
        if line.startswith("BOOT_METHOD="):
            boot = line.split("=", 1)[1].split("#")[0].strip().strip('"')
    if not boot:
        raise SystemExit("lock: no BOOT_METHOD in devices/%s/device.env" % target["device"])
    layers = ["base", "desktops/" + target["desktop"], "boot/" + boot] + extra + ["devices/" + target["device"]]
    return layer_sources(layers, "image", with_build=True)


def target_steps(target):
    steps = []
    for src in target_sources(target):
        path = ul.REPO / src
        text = path.read_text(encoding="utf-8")
        if path.name.startswith("packages"):
            steps.append(packages_step(text, src))
        else:
            steps += extract_steps(text, src)
    return steps


class Unresolvable(Exception):
    """The target's steps don't resolve (e.g. a package left Fedora)."""


# --------------------------------------------------------------- podman

def run(cmd, **kw):
    kw.setdefault("check", True)
    return subprocess.run(cmd, **kw)


def pull(ref):
    print("lock: pulling %s" % ref, file=sys.stderr)
    run([PODMAN, "pull", "-q", ref], stdout=subprocess.DEVNULL)


def image_info(ref):
    fmt = ('{{.Digest}}\t{{index .Labels "org.opencontainers.image.version"}}'
           '\t{{.Architecture}}')
    out = run([PODMAN, "image", "inspect", "--format", fmt, ref],
              capture_output=True, text=True).stdout.strip()
    digest, version, arch = (out.split("\t") + ["", "", ""])[:3]
    name = ref.rsplit("@", 1)[0]
    if ":" in name.rsplit("/", 1)[-1]:
        name = name.rsplit(":", 1)[0]
    info = {"image": ref, "digest": digest, "pinned": "%s@%s" % (name, digest)}
    if version and version != "<no value>":
        info["version"] = version
    if arch not in ("arm64", "aarch64"):
        raise SystemExit("lock: %s is %s, not arm64 (we only lock aarch64)" % (ref, arch))
    return info


# Copy the image's rpmdb into an installroot, so python3-libdnf5 (installed
# next, if missing) doesn't change what the resolution sees as installed.
CONTAINER_SCRIPT = r"""
set -euo pipefail
[ "$(uname -m)" = aarch64 ] || { echo "dnf-helper: not aarch64" >&2; exit 3; }
db=$(rpm --eval %_dbpath)
mkdir -p "/tmp/root$(dirname "$db")"
cp -a "$db" "/tmp/root$db"
if ! python3 -c 'import libdnf5' 2>/dev/null; then
    dnf5 -q -y --setopt=install_weak_deps=False install python3-libdnf5 >&2
fi
exec python3 /fap/dnf-helper.py
"""


def helper(image, request):
    cmd = [PODMAN, "run", "--rm", "-i", "--pull=never",
           "-v", "%s:/fap:ro" % HELPER_DIR,
           "-v", "%s:/var/cache/libdnf5" % CACHE_VOLUME,
           image, "bash", "-c", CONTAINER_SCRIPT]
    p = run(cmd, input=json.dumps(request), capture_output=True, text=True, check=False)
    if p.returncode != 0:
        sys.stderr.write(p.stderr)
        raise SystemExit("lock: dnf-helper failed in %s (exit %d)" % (image, p.returncode))
    return json.loads(p.stdout)


def kernel_packages(image):
    qf = r"%{NAME}\t%{EPOCHNUM}:%{VERSION}-%{RELEASE}\t%{ARCH}\t%{SOURCERPM}\n"
    out = run([PODMAN, "run", "--rm", "--pull=never", image, "rpm", "-qa", "--qf", qf, "kernel*"],
              capture_output=True, text=True).stdout
    return parse_rpmqa(out)


def parse_rpmqa(text):
    pkgs = []
    for line in text.splitlines():
        parts = line.split("\t")
        if len(parts) != 4 or parts[2] == "(none)":
            continue
        name, evr, arch, src = parts
        if evr.startswith("0:"):
            evr = evr[2:]
        pkgs.append({"name": name, "evr": evr, "arch": arch, "source": src})
    return sorted(pkgs, key=lambda p: (p["name"], p["arch"], p["evr"]))


# --------------------------------------------------------------- output

def dump_yaml(data):
    import yaml
    # One package per line (flow mappings): small, readable git diffs.
    return yaml.safe_dump(data, sort_keys=False, default_flow_style=None, width=4096)


def versionlock_toml(lock):
    """dnf5's /etc/dnf/versionlock.toml: every package our steps install
    or upgrade, locked to the resolved version. Base packages are pinned by
    the base image digest; dnf can't touch them without a locked package
    needing it, and the locked set needs exactly what it needed at lock time."""
    out = [HEADER + 'version = "1.0"', ""]
    seen = set()
    for p in lock.get("packages") or []:
        key = (p["name"], p["evr"])
        if key in seen:
            continue
        seen.add(key)
        out += ["[[packages]]", 'name = "%s"' % p["name"],
                'comment = "%s"' % lock["target"],
                "[[packages.conditions]]", 'key = "evr"', 'comparator = "="',
                'value = "%s"' % p["evr"], ""]
    return "\n".join(out)


def images_env(lock):
    lines = [HEADER.rstrip("\n"), "# Image references by digest for a pinned build."]
    if lock.get("base"):
        lines.append("BASE_IMAGE=%s" % lock["base"]["pinned"])
    if lock.get("kernel_image"):
        lines.append("KERNEL_IMAGE=%s" % lock["kernel_image"]["pinned"])
    return "\n".join(lines) + "\n"


def lock_target(name, target, pulled):
    steps = target_steps(target)
    for s in steps:
        if s["skipped"]:
            print("lock: %s: %s: not resolvable, skipped: %s"
                  % (name, s["where"], " ".join(s["skipped"])), file=sys.stderr)
    for ref in filter(None, [target["base"], target.get("kernel_image")]):
        if ref not in pulled:
            pull(ref)
            pulled.add(ref)
    base = image_info(target["base"])
    request = {"cmd": "resolve", "installroot": "/tmp/root",
               "releasever": str(target.get("releasever", "45")),
               "weak_deps": any(s["weak_deps"] for s in steps if s["action"] == "install"),
               "steps": [{"action": s["action"], "specs": s["specs"]} for s in steps if s["specs"]]}
    res = helper(target["base"], request)
    if not res.get("ok"):
        raise Unresolvable("\n".join(p for p in res["problems"] if "already installed" not in p))
    base["packages"] = res.get("base") or []
    lock = {
        "lockfileVersion": 1,
        "target": name,
        "description": target.get("description", ""),
        "arch": ARCH,
        "weak_deps": request["weak_deps"],
        "steps": [{"where": s["where"], "action": s["action"], "specs": s["specs"]} for s in steps],
    }
    if target.get("kernel_image"):
        k = image_info(target["kernel_image"])
        k["packages"] = kernel_packages(target["kernel_image"])
        lock["kernel_image"] = k
    lock["base"] = base
    lock["packages"] = res["packages"]
    lock["removed"] = res["removed"]
    return lock


def write_lock(lock, out_dir):
    out_dir.mkdir(parents=True, exist_ok=True)
    t = lock["target"]
    (out_dir / ("%s.rpms.lock.yaml" % t)).write_text(HEADER + dump_yaml(lock), encoding="utf-8")
    (out_dir / ("%s.versionlock.toml" % t)).write_text(versionlock_toml(lock), encoding="utf-8")
    (out_dir / ("%s.images.env" % t)).write_text(images_env(lock), encoding="utf-8")


def load_locks(lock_dir):
    """{target: lock} for every *.rpms.lock.yaml in a directory."""
    locks = {}
    for f in sorted(Path(lock_dir).glob("*.rpms.lock.yaml")):
        data = ul.load_yaml(f)
        locks[data["target"]] = data
    return locks


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--target", action="append", help="target name (repeatable; default: all)")
    ap.add_argument("--out", type=Path, default=ul.LOCK_DIR, help="output directory (default lock/)")
    ap.add_argument("--list-steps", action="store_true", help="print the extracted steps and exit")
    ap.add_argument("--failures", type=Path, help="write {target: problems} JSON here")
    ap.add_argument("--prune-images", action="store_true",
                    help="remove each pulled image after use (CI: small disks)")
    args = ap.parse_args(argv)
    targets = ul.load_yaml(TARGETS)["targets"]
    names = args.target or list(targets)
    for n in names:
        if n not in targets:
            raise SystemExit("lock: no target %r in %s" % (n, TARGETS))
    if args.list_steps:
        for n in names:
            print("%s:" % n)
            for s in target_steps(targets[n]):
                print("  %-55s %-7s weak=%-5s %s" % (s["where"], s["action"], s["weak_deps"],
                                                       " ".join(s["specs"])))
        return 0
    pulled = set()
    failures = {}
    for n in names:
        try:
            lock = lock_target(n, targets[n], pulled)
        except Unresolvable as e:
            # Keep the old lock; report and go on with the other targets.
            failures[n] = str(e)
            print("lock: %s does not resolve (old lock kept):\n%s" % (n, e), file=sys.stderr)
            continue
        write_lock(lock, args.out)
        print("lock: %s: %d packages on top of %s (%d base packages)"
              % (n, len(lock["packages"]), lock["base"]["pinned"], len(lock["base"]["packages"])),
              file=sys.stderr)
        if args.prune_images:
            # Keep images a later target still needs.
            later = {r for m in names[names.index(n) + 1:]
                     for r in (targets[m]["base"], targets[m].get("kernel_image")) if r}
            for ref in list(pulled - later):
                run([PODMAN, "rmi", "-f", ref], check=False, stdout=subprocess.DEVNULL)
                pulled.discard(ref)
    if args.failures:
        args.failures.write_text(json.dumps(failures, indent=1) + "\n", encoding="utf-8")
    return 1 if failures else 0


if __name__ == "__main__":
    sys.exit(main())
